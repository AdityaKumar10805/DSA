class Solution {
public:
    long long countCommas(long long n) {
        if(n<1000){
            return 0;
        }
        else if(n>=1000&&n<1000000){
            return n-1000+1;//1
        }else if(n>=1000000&&n<1000000000){

            return (1000000-1000)+(n-1000000+1)*2;//2
        }else if(n>=1000000000&&n<1000000000000){
            return (1000000-1000)+(1000000000-1000000)*2+3*(n-1000000000+1);//3
        }else if(n>=1000000000000&&n<1000000000000000){
            return (1000000-1000)+(1000000000-1000000)*2+3*(1000000000000-1000000000)+4*(n-1000000000000+1);//4
        }
        return (1000000-1000)+(1000000000-1000000)*2+3*(1000000000000-1000000000)+4*(1000000000000000-1000000000000)+1*5;
    }
};